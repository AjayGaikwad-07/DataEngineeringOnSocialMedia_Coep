# ── 1. PostgreSQL schema demonstration ───────────────────────────────────────
print("\n[SECTION 1] PostgreSQL Schema")
print("-"*60)
SCHEMA_SQL = """
-- Database: socialmedia
-- Created by: spark/process_and_load.py

CREATE TABLE IF NOT EXISTS posts (
    id              BIGINT PRIMARY KEY,
    username        TEXT,
    text            TEXT,
    likes           INT            DEFAULT 0,
    retweets        INT            DEFAULT 0,
    created_at      TEXT,
    post_hour       INT,
    engagement      INT,
    sentiment_score FLOAT,
    sentiment_label TEXT,
    processed_at    TIMESTAMP      DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS hashtag_counts (
    hashtag   TEXT PRIMARY KEY,
    count     INT  NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Indexes for dashboard query performance
CREATE INDEX IF NOT EXISTS idx_posts_username     ON posts(username);
CREATE INDEX IF NOT EXISTS idx_posts_hour         ON posts(post_hour);
CREATE INDEX IF NOT EXISTS idx_posts_sentiment    ON posts(sentiment_label);
CREATE INDEX IF NOT EXISTS idx_hashtag_count      ON hashtag_counts(count DESC);
"""
print(SCHEMA_SQL)

# ── 2. Dashboard SQL queries ──────────────────────────────────────────────────
print("[SECTION 2] Dashboard SQL Queries")
print("-"*60)
QUERIES = {
    "Total Posts": "SELECT COUNT(*) AS total_posts FROM posts;",
    "Top Users": """
    SELECT username, COUNT(*) AS post_count,
           ROUND(AVG(engagement),1) AS avg_engagement
    FROM   posts
    GROUP  BY username
    ORDER  BY post_count DESC
    LIMIT  10;""",
    "Trending Hashtags": """
    SELECT hashtag, count
    FROM   hashtag_counts
    ORDER  BY count DESC
    LIMIT  15;""",
    "Most Active Hours": """
    SELECT post_hour, COUNT(*) AS posts
    FROM   posts
    WHERE  post_hour IS NOT NULL
    GROUP  BY post_hour
    ORDER  BY post_hour;""",
    "Sentiment Breakdown": """
    SELECT sentiment_label, COUNT(*) AS total,
           ROUND(COUNT(*)*100.0 / SUM(COUNT(*)) OVER (), 2) AS pct
    FROM   posts
    GROUP  BY sentiment_label;""",
}
for title, sql in QUERIES.items():
    print(f"\n  -- {title}")
    print(f"  {sql.strip()}")

# ── 3. Load data (Spark CSV or synthetic fallback) ────────────────────────────
print("\n[SECTION 3] Loading Processed Data")
print("-"*60)

posts_csv    = os.path.join(SPARK_OUT, "processed_posts.csv")
hashtags_csv = os.path.join(SPARK_OUT, "top_hashtags.csv")

if os.path.exists(posts_csv):
    posts = pd.read_csv(posts_csv)
    print(f"  [OK] Loaded posts from {posts_csv}  ({len(posts)} rows)")
else:
    # Generate synthetic data matching the project schema
    print("  [INFO] Spark output not found — using synthetic data")
    random.seed(42)
    users     = [f"User{i}" for i in range(1, 26)]
    sentiments = ["positive", "negative", "neutral"]
    sent_weights = [0.45, 0.25, 0.30]
    records = []
    base = datetime(2026, 8, 1, 0, 0)
    for i in range(2000):
        sl = random.choices(sentiments, sent_weights)[0]
        ss = 0.65 if sl == "positive" else (-0.60 if sl == "negative" else 0.05)
        ts = base + timedelta(hours=random.randint(0, 24*60))
        likes    = random.randint(0, 500)
        retweets = random.randint(0, 200)
        records.append({
            "id": 10001 + i,
            "username": random.choice(users),
            "text": f"Sample post {i}",
            "likes": likes,
            "retweets": retweets,
            "created_at": ts.isoformat(),
            "post_hour": ts.hour,
            "engagement": likes + retweets,
            "sentiment_score": ss,
            "sentiment_label": sl,
        })
    posts = pd.DataFrame(records)

if os.path.exists(hashtags_csv):
    hashtags = pd.read_csv(hashtags_csv)
    print(f"  [OK] Loaded hashtags from {hashtags_csv}")
else:
    tag_names = ["#AI", "#MachineLearning", "#BigData", "#DataScience",
                 "#Kafka", "#Spark", "#Python", "#DataEngineering",
                 "#CloudComputing", "#Automation", "#NLP", "#DeepLearning",
                 "#Analytics", "#ETL", "#Streaming"]
    counts = sorted([random.randint(50, 400) for _ in tag_names], reverse=True)
    hashtags = pd.DataFrame({"hashtag": tag_names, "count": counts})
    print("  [INFO] Using synthetic hashtag data")

total_posts = len(posts)
print(f"\n  Total posts in dataset : {total_posts}")
print(f"  Unique users           : {posts['username'].nunique()}")
print(f"  Columns                : {list(posts.columns)}")

# ── 4. Generate Charts ────────────────────────────────────────────────────────
print("\n[SECTION 4] Generating Dashboard Charts")
print("-"*60)
sns.set_theme(style="whitegrid", palette="muted")
plt.rcParams.update({"font.size": 11, "axes.titlesize": 13})

COLORS = ["#4C72B0", "#DD8452", "#55A868", "#C44E52", "#8172B3",
          "#937860", "#DA8BC3", "#8C8C8C", "#CCB974", "#64B5CD"]

# ---- Chart 1: Top Users -----
top_users = posts["username"].value_counts().head(10).reset_index()
top_users.columns = ["username", "post_count"]

fig, ax = plt.subplots(figsize=(9, 5))
bars = ax.barh(top_users["username"][::-1], top_users["post_count"][::-1],
               color=COLORS[:len(top_users)])
ax.bar_label(bars, fmt="%d", padding=3)
ax.set_title("Top 10 Users by Post Count", fontweight="bold")
ax.set_xlabel("Number of Posts")
ax.set_ylabel("Username")
plt.tight_layout()
chart1 = os.path.join(OUT_DIR, "top_users.png")
plt.savefig(chart1, dpi=150)
plt.close()
print(f"  [OK] Chart 1 saved: {chart1}")

# ---- Chart 2: Trending Hashtags -----
ht_plot = hashtags.head(15).copy()
# strip '#' prefix if present for cleaner display
ht_plot["label"] = ht_plot["hashtag"].str.lstrip("#")

fig, ax = plt.subplots(figsize=(9, 6))
bars = ax.barh(ht_plot["label"][::-1], ht_plot["count"][::-1],
               color="#4C72B0")
ax.bar_label(bars, fmt="%d", padding=3)
ax.set_title("Top 15 Trending Hashtags", fontweight="bold")
ax.set_xlabel("Frequency")
ax.set_ylabel("Hashtag")
plt.tight_layout()
chart2 = os.path.join(OUT_DIR, "trending_hashtags.png")
plt.savefig(chart2, dpi=150)
plt.close()
print(f"  [OK] Chart 2 saved: {chart2}")

# ---- Chart 3: Most Active Hours -----
if "post_hour" in posts.columns and posts["post_hour"].notna().any():
    posts["post_hour"] = pd.to_numeric(posts["post_hour"], errors="coerce")
    hourly = posts.groupby("post_hour").size().reindex(range(24), fill_value=0)
    fig, ax = plt.subplots(figsize=(11, 5))
    ax.bar(hourly.index, hourly.values, color="#55A868", edgecolor="white")
    ax.set_title("Most Active Posting Hours (UTC)", fontweight="bold")
    ax.set_xlabel("Hour of Day (0-23)")
    ax.set_ylabel("Number of Posts")
    ax.set_xticks(range(24))
    ax.set_xticklabels([f"{h:02d}:00" for h in range(24)], rotation=45, ha="right")
    plt.tight_layout()
    chart3 = os.path.join(OUT_DIR, "active_hours.png")
    plt.savefig(chart3, dpi=150)
    plt.close()
    print(f"  [OK] Chart 3 saved: {chart3}")
else:
    print("  [SKIP] No post_hour column — skipping active-hours chart")
    chart3 = None

# ---- Chart 4: Sentiment Breakdown -----
if "sentiment_label" in posts.columns:
    sent_counts = posts["sentiment_label"].value_counts()
    colors_pie = {"positive": "#55A868", "neutral": "#8C8C8C", "negative": "#C44E52"}
    clrs = [colors_pie.get(l, "#4C72B0") for l in sent_counts.index]
    fig, ax = plt.subplots(figsize=(6, 6))
    wedges, texts, autotexts = ax.pie(
        sent_counts.values,
        labels=sent_counts.index,
        autopct="%1.1f%%",
        colors=clrs,
        startangle=140,
        pctdistance=0.82,
    )
    for at in autotexts:
        at.set_fontsize(12)
        at.set_fontweight("bold")
    ax.set_title("Sentiment Breakdown", fontweight="bold")
    plt.tight_layout()
    chart4 = os.path.join(OUT_DIR, "sentiment_breakdown.png")
    plt.savefig(chart4, dpi=150)
    plt.close()
    print(f"  [OK] Chart 4 saved: {chart4}")
else:
    print("  [SKIP] No sentiment_label column")
    chart4 = None

